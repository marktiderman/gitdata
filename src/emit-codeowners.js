/**
 * `gitdata emit codeowners` — the still-unbuilt half of north star #5: "based on folders we can
 * declare code owners."
 *
 * Ownership is declared as data, the same way everything else in this project is: a table folder
 * that wants reviewers gets a `_owners.yml` beside its rows —
 *
 *   data/features/_owners.yml
 *     owners:
 *       - "@alice"
 *       - "@bob"
 *
 * — using the `_`-prefix convention `src/load.js` already reserves for non-rows (`_template.md`,
 * `_views/`, `_schema/`). This module walks `data/` with `load()` (never its own readdir — one
 * definition of "what is a table" for the whole engine), reads each table's `_owners.yml` if
 * present, and renders a GitHub-format CODEOWNERS block: `path/pattern @owner1 @owner2`.
 *
 * A table with no `_owners.yml` gets no line. Ownership is opt-in per table, never inferred from
 * git blame or who happens to own neighboring code — inferring policy is exactly the kind of
 * judgment call CLAUDE.md's "The law" reserves for GitHub, not this tool.
 *
 * An optional `data/_owners.yml` (same shape, at the data root) sets a repo-wide default for
 * `data/**`; it is emitted first, and GitHub's own last-match-wins rule is what lets a later,
 * more specific table line override it. gitdata does not implement precedence — CODEOWNERS
 * already has one.
 *
 * This module only knows about `data/`. Ownership of files outside it (`/README.md`, a repo-wide
 * catch-all `*`) is not gitdata's domain and stays hand-authored in the same file gitdata writes
 * to — see the CLI layer's write/--check behaviour in `cli.js` for how the two coexist.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";

import { parse as parseYaml } from "yaml";

import { load } from "./load.js";

export class EmitError extends Error {}

/**
 * The generated file says where it came from, out of the data root it was actually given rather
 * than a hardcoded `data/`. A repo may keep more than one store, and a header naming the wrong one
 * sends the reader to edit an `_owners.yml` that does not govern these lines — docs drift, in the
 * one artifact this tool writes about who may approve a change. Renders identically to before for
 * the default root, so no existing CODEOWNERS moves a byte.
 */
const header = (dataRel) =>
  [
    `# CODEOWNERS — generated by \`gitdata emit codeowners\` from ${dataRel}/<table>/_owners.yml.`,
    "# Do not hand-edit: `gitdata emit codeowners --check` fails if you do.",
    "# Declare ownership as data — add or edit a table's _owners.yml, then re-run.",
  ].join("\n");

/** POSIX-separated path relative to `base` — CODEOWNERS patterns are always `/`, never `\`. */
function posixRelative(base, target) {
  return relative(base, target).split(sep).join("/");
}

/**
 * Read one `_owners.yml`. Returns `null` if it does not exist — absence means "no line", not an
 * error. A file that exists but is malformed fails loud and names itself, the same contract
 * `loadViewSpecs` holds for a view spec.
 */
function readOwners(path, label) {
  if (!existsSync(path)) return null;

  let doc;
  try {
    doc = parseYaml(readFileSync(path, "utf8"));
  } catch (cause) {
    throw new EmitError(`${label}: unparseable YAML — ${cause.message}`);
  }

  const owners = doc?.owners;
  if (!Array.isArray(owners) || owners.length === 0) {
    throw new EmitError(`${label}: "owners" must be a non-empty list of GitHub handles or teams`);
  }
  for (const o of owners) {
    if (typeof o !== "string" || o.trim() === "") {
      throw new EmitError(`${label}: every "owners" entry must be a non-empty string`);
    }
  }
  return owners;
}

/**
 * CODEOWNERS lines for every table (and the optional repo-wide default) that declares ownership,
 * in deterministic order: the default first, then one line per table sorted by name — never
 * directory order, per law 4.
 *
 * @param {{dataRoot: string, repoRoot: string}} opts
 * @returns {string[]}
 */
export function codeownersLines({ dataRoot, repoRoot }) {
  const dataRel = posixRelative(repoRoot, dataRoot);
  const lines = [];

  const rootOwners = readOwners(join(dataRoot, "_owners.yml"), `${dataRel}/_owners.yml`);
  if (rootOwners) lines.push(`/${dataRel}/** ${rootOwners.join(" ")}`);

  if (existsSync(dataRoot)) {
    for (const table of [...load(dataRoot).keys()].sort()) {
      const owners = readOwners(join(dataRoot, table, "_owners.yml"), `${dataRel}/${table}/_owners.yml`);
      if (owners) lines.push(`/${dataRel}/${table}/** ${owners.join(" ")}`);
    }
  }

  return lines;
}

/**
 * The full CODEOWNERS text gitdata owns for `data/`, or `null` if nothing declares ownership —
 * the signal `emitCodeowners` uses to leave a repo with no `_owners.yml` files alone rather than
 * writing an empty, pointless artifact.
 *
 * @param {{dataRoot: string, repoRoot: string}} opts
 */
export function renderCodeowners({ dataRoot, repoRoot }) {
  const lines = codeownersLines({ dataRoot, repoRoot });
  if (lines.length === 0) return null;
  return `${header(posixRelative(repoRoot, dataRoot))}\n\n${lines.join("\n")}\n`;
}

/**
 * Render, then write or check — the same write-or-`--check` split `rollup()` uses, applied to
 * permissions instead of content (north star #6, "driftproof," read as a law about who as much
 * as what).
 *
 * @param {{dataRoot: string, repoRoot: string, outPath: string, check?: boolean}} opts
 * @returns {{status: "written"|"unchanged"|"drifted"|"missing"|"empty", out: string, compiled?: string, committed?: string|null}}
 */
export function emitCodeowners({ dataRoot, repoRoot, outPath, check = false }) {
  const compiled = renderCodeowners({ dataRoot, repoRoot });
  if (compiled === null) return { status: "empty", out: outPath };

  const committed = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;

  if (check) {
    const status = committed === null ? "missing" : committed === compiled ? "unchanged" : "drifted";
    return { status, out: outPath, compiled, committed };
  }

  if (committed === compiled) return { status: "unchanged", out: outPath };

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, compiled, "utf8");
  return { status: "written", out: outPath };
}
